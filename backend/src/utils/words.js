// Получить слово для текущего 2-часового слота
function getWordForSlot() {
  const now = new Date();
  const h = now.getUTCHours();
  const day = now.toISOString().slice(0, 10);
  const slot = Math.floor(h / 2);
  // Простой хеш из даты+слота для выбора слова
  let hash = 0;
  const key = day + '_' + slot;
  for (let i = 0; i < key.length; i++) {
    hash = ((hash << 5) - hash + key.charCodeAt(i)) | 0;
  }
  const idx = Math.abs(hash) % WORDS.length;
  return WORDS[idx].toUpperCase();
}

